"""JS localeCompare replication for the workspace/capsule sort sites.

The Node reference sorts nodes, edges, claims, unknowns, and remotes with
String.prototype.localeCompare (ICU collation - NOT codepoint order: "a"
sorts before "B"). Claim/node order feeds every capsule and workspace
fingerprint, so the Python port must reproduce that ordering exactly.

The table below is an EMPIRICAL pin extracted from Node itself
(python/parity/extract_collation.mjs): a two-level UCA-style model -
primary group order, tertiary order within a group (case pairs), completely
ignorable characters skipped - verified against localeCompare over a full
pairwise probe set (~2.1M pairs) at extraction time, and re-verified
cross-language by the parity harness.

Characters OUTSIDE the pinned domain raise CollationDomainError: the port
refuses to guess ICU's order for characters the oracle never pinned (fail
loud, never silently diverge). The domain covers ASCII printable, tab/CR/LF,
and Latin-1 - everything git output, paths, facts, and claim text contain
in this system's practice.

Generated by scratchpad gen_collation_py.py from collation-table.json; do
not hand-edit the tables. Regenerate only if the Node reference's observed
collation changes (which would itself be a frozen-contract event).
"""

