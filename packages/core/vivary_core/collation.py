_WEIGHTS = {}
for _p, _group in enumerate(_GROUPS, start=1):
    for _t, _cp in enumerate(_group, start=1):
        _WEIGHTS[_cp] = (_p, _t)


class CollationDomainError(ValueError):
    """A character outside the empirically-pinned collation domain."""


def _weight_seqs(value: str):
    primary = []
    tertiary = []
    for ch in value:
        cp = ord(ch)
        if cp in _IGNORABLE:
            continue
        try:
            p, t = _WEIGHTS[cp]
        except KeyError:
            raise CollationDomainError(
                f"character U+{cp:04X} ({ch!r}) is outside the pinned collation domain; "
                "the Node oracle's ordering for it was never extracted"
            ) from None
        primary.append(p)
        tertiary.append(t)
    return primary, tertiary


def _cmp_seq(a: list, b: list) -> int:
    for i in range(max(len(a), len(b))):
        av = a[i] if i < len(a) else 0
        bv = b[i] if i < len(b) else 0
        if av != bv:
            return -1 if av < bv else 1
    return 0


def locale_compare(a: str, b: str) -> int:
    """JS `a.localeCompare(b)` (sign only) over the pinned domain."""
    ap, at = _weight_seqs(a)
    bp, bt = _weight_seqs(b)
    return _cmp_seq(ap, bp) or _cmp_seq(at, bt)


def locale_sort_key(value: str):
    """Sort key equivalent of locale_compare for `sorted(key=...)`."""
    primary, tertiary = _weight_seqs(value)
    return (tuple(primary), tuple(tertiary))


locale_cmp_key = cmp_to_key(locale_compare)
